function trace(path,points,size){
  points.forEach(([px,py],i)=>{
    const x=((px+.5)/300-.5)*size,y=(.5-(py+.5)/300)*size;
    if(i===0)path.moveTo(x,y);
    else path.lineTo(x,y);
  });
  path.closePath();
  return path;
}

export function createLisbonSignGeometry(id,size,depth){
  const shapes=outlines[id].map(([exterior,...interior])=>{
    const shape=trace(new T.Shape(),exterior,size);
    shape.holes=interior.map(hole=>trace(new T.Path(),hole,size));
    return shape;
  });
  const geometry=new T.ExtrudeGeometry(shapes,{depth,bevelEnabled:false});
  // The same artwork spans the face and continues along its cut edge.
  const position=geometry.getAttribute('position'),uv=geometry.getAttribute('uv');
  for(let i=0;i<position.count;i++){
    uv.setXY(i,position.getX(i)/size+.5,position.getY(i)/size+.5);
  }
  geometry.computeBoundingBox();
  return geometry;
}
