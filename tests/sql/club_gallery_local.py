ROOT = Path(__file__).resolve().parents[2] / 'backend/supabase/migrations'


def function(name, migration):
    source = (ROOT / migration).read_text()
    match = re.search(r'(?im)^create\s+or\s+replace\s+function\s+public\.' + re.escape(name) + r'\s*\(', source)
    if not match:
        raise ValueError(f'Missing {name} in {migration}')
    opening = re.search(r'\bas\s+(\$\w*\$)', source[match.end():], re.I)
    start = match.end() + opening.end()
    delimiter = opening.group(1)
    end = source.index(delimiter, start) + len(delimiter)
    return f'-- Actual {name}: {migration}\n' + source[match.start():end] + ';\n'


def table(name, migration):
    source = (ROOT / migration).read_text()
    match = re.search(r'(?im)^create\s+table\s+if\s+not\s+exists\s+public\.' + re.escape(name) + r'\s*\(', source)
    if not match:
        raise ValueError(f'Missing table {name} in {migration}')
    end = source.index(';', match.end()) + 1
    return f'-- Actual initial {name} DDL: {migration}\n' + source[match.start():end] + '\n'


